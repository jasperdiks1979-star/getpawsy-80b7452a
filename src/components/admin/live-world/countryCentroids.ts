/** Country name -> centroid, tolerant of casing/whitespace. Null when unknown. */
export function countryPoint(name: string | null | undefined): CountryPoint | null {
  if (!name) return null;
  const direct = COUNTRY_POINTS[name];
  if (direct) return direct;
  const key = name.trim().toLowerCase();
  for (const [k, v] of Object.entries(COUNTRY_POINTS)) {
    if (k.toLowerCase() === key) return v;
  }
  return null;
}

/** Regional-indicator flag emoji for an ISO-2 code. */
export function flagEmoji(iso: string | null | undefined): string {
  if (!iso || iso.length !== 2) return "\u{1F3F3}";
  return String.fromCodePoint(...[...iso.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}

/** Equirectangular projection into the 1000x500 world viewBox. */
export function projectXY(lon: number, lat: number): { x: number; y: number } {
  return { x: ((lon + 180) / 360) * 1000, y: ((90 - lat) / 180) * 500 };
}
